# Nama variabel ditambah 4 digit nim terakhir contoh: ulang_2022
# Program ini menggunakn fungsi input()

ulang_2022 = int(input("Masukkan jumlah perulangan :"))
print("perulangan ke-0 sampai ke-", ulang_2022-1)
for i_2022 in range(ulang_2022):
    print(i_2022, end=" ")
print()
print(" Perulangan ke-1 sampai ke-", ulang_2022)
for i_2022 in range(1, ulang_2022+1):
    print(i_2022, end=" ")